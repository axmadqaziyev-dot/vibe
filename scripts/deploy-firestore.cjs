const fs = require('fs');
const base = 'C:/Users/user/AppData/Roaming/npm/node_modules/firebase-tools/lib/';
const auth = require(base+'auth');
const rules = require(base+'gcp/rules');
(async () => {
 const account = auth.getGlobalDefaultAccount();
 if (!account) throw Error('Firebase login required');
 await require(base+'requireAuth').requireAuth({project:'vibe-f9d13',...account});
 const backup=JSON.parse(fs.readFileSync('firestore.remote.backup.json','utf8').replace(/^\uFEFF/,''));
 const current=(await rules.listAllReleases('vibe-f9d13')).find(r=>r.name==='projects/vibe-f9d13/releases/cloud.firestore');
 if(current?.rulesetName!==backup.release.rulesetName) throw Error('Remote rules changed');
 const files=[{name:'firestore.rules',content:fs.readFileSync('firestore.rules','utf8').replace(/^\uFEFF/,'')}];
 const validation=await rules.testRuleset('vibe-f9d13',files);
 if((validation.body.issues||[]).some(i=>i.severity==='ERROR')) throw Error('Validation failed');
 const name=await rules.createRuleset('vibe-f9d13',files);
 await rules.updateRelease('vibe-f9d13',name,'cloud.firestore');
 const release=(await rules.listAllReleases('vibe-f9d13')).find(r=>r.name==='projects/vibe-f9d13/releases/cloud.firestore');
 if(release?.rulesetName!==name) throw Error('Release verification failed');
 const deployed=await rules.getRulesetContent(name);
 if(deployed[0].content!==files[0].content) throw Error('Content verification failed');
 fs.writeFileSync('firestore.deployment.json',JSON.stringify({release,verifiedAt:new Date().toISOString()},null,2));
 console.log('Firestore call rules deployed and verified in vibe-f9d13.');
})().catch(e=>{console.error(e.message);process.exitCode=1;});
